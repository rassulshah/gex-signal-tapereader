bool first_extreme_probabilities(const Features& x,Probabilities& p){
  for(double v:x) if(!std::isfinite(v)) return false;
  auto s=raw_scores(x);
  const double temperature=1.1254127252571318;
  const Probabilities bias={0,0.10637088411083417,-0.03895661834097594};
  for(int k=0;k<3;k++) s[k]=s[k]/temperature+bias[k];
  double mx=*std::max_element(s.begin(),s.end());double total=0;
  for(int k=0;k<3;k++){p[k]=std::exp(s[k]-mx);total+=p[k];}
  for(double &v:p) v/=total;return true;
}
